// @ts-check
/**
 * makeReel: inputs → staged media → (prepare) → build → compile → reels/<name>.html
 * (→ render). Library entry point shared by `reelclaw make`, `batch` and tests.
 */
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { isAbsolute, join, resolve } from "node:path";
import { compile } from "./compile.mjs";
import { ReelclawError } from "./errors.mjs";
import { CANVAS, SAFE_BAND } from "./geometry.mjs";
import { flagName, isMediaKind, parseValues } from "./inputs.mjs";
import { loadTemplate } from "./loader.mjs";
import { consoleLogger, displayPath } from "./log.mjs";
import { deriveMedia, stageMedia } from "./media/stage.mjs";
import { ensureProject, kebab, nextReelName } from "./project.mjs";
import { lintReel, renderReel, runHyperframes } from "./render.mjs";

/** @typedef {import('./log.mjs').Logger} Logger */
/** @typedef {import('./render.mjs').Quality} Quality */
/** @typedef {import('./types.mjs').MediaRef} MediaRef */
/** @typedef {import('./types.mjs').MediaKind} MediaKind */
/** @typedef {import('./template.mjs').Template<any, any>} AnyTemplate */

/**
 * @typedef {object} MakeOptions
 * @property {string} root            reel project root (assets/, reels/, renders/ live here)
 * @property {string | AnyTemplate} template  id, folder path, or an already-loaded template
 * @property {Record<string, unknown>} values  raw inputs (CLI flags or props JSON; camelCase or kebab-case keys)
 * @property {string} [name]          reel name; default `<template-id>-N`
 * @property {boolean} [render]
 * @property {Quality} [quality]
 * @property {number|'auto'} [workers]
 * @property {boolean} [lint]        run `hyperframes lint` on the output (default true; ~0.5s)
 * @property {string} [cwd]           base for relative media paths (default: process.cwd())
 * @property {Logger} [log]
 */

/**
 * @typedef {object} MakeResult
 * @property {string} name
 * @property {string} templateId
 * @property {string} html       absolute path of reels/<name>.html
 * @property {string} props      absolute path of reels/<name>.json
 * @property {number} duration   seconds
 * @property {string[]} warnings
 * @property {string} [output]   absolute path of the MP4 when rendered
 */

/**
 * @param {MakeOptions} o
 * @returns {Promise<MakeResult>}
 */
export async function makeReel(o) {
  const log = o.log ?? consoleLogger;
  const root = resolve(o.root);
  const cwd = o.cwd ?? process.cwd();
  const template = typeof o.template === "string" ? (await loadTemplate(o.template, root)).template : o.template;

  const parsed = parseValues(template.inputs, o.values, { templateId: template.id });
  const name = o.name ?? nextReelName(root, kebab(template.id));
  if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) {
    throw new ReelclawError(`invalid --name "${name}"`, { hint: "use kebab-case: lowercase letters, digits and dashes" });
  }
  await ensureProject(root);

  /** @type {string[]} */
  const warnings = [];
  const warn = (/** @type {string} */ m) => { warnings.push(m); log.warn(m); };

  const inputs = await stageInputs({ template, values: parsed, root, cwd, log });

  const prepared = template.prepare
    ? await template.prepare({
        inputs,
        root,
        cwd,
        media: {
          derive: (d) => deriveMedia({ root, ...d }),
          stage: (value, kind, label) => stageMedia({ root, value, kind, label, cwd, log }),
        },
        hyperframes: async (args) => {
          const code = await runHyperframes(args, { cwd: root });
          if (code !== 0) throw new ReelclawError(`hyperframes ${args[0]} failed (exit ${code})`);
        },
        log,
        warn,
      })
    : {};

  const tl = template.build({ inputs, prepared: prepared ?? {}, canvas: CANVAS, safe: SAFE_BAND, warn });
  if (!tl || !Array.isArray(tl.clips)) {
    throw new ReelclawError(`template "${template.id}": build() must return timeline([...])`);
  }
  const result = compile(tl, {
    name,
    banner: `Generated by reelclaw from template "${template.id}" (inputs: reels/${name}.json). Edit freely; making a reel with the same name again overwrites this file.`,
  });
  for (const w of result.warnings) warn(w);

  const html = join(root, "reels", `${name}.html`);
  const props = join(root, "reels", `${name}.json`);
  await writeFile(html, result.html);
  await writeFile(props, `${JSON.stringify({ template: template.id, inputs: propsFor(template, parsed, inputs) }, null, 2)}\n`);
  log.success(`reels/${name}.html  (${result.timeline.duration}s)`);

  if (o.lint !== false) {
    const errors = (await lintReel(root, name)).filter((f) => f.severity === "error");
    if (errors.length) {
      throw new ReelclawError(`reels/${name}.html fails HyperFrames lint:\n  - ${errors.map((f) => `${f.code}: ${f.message}`).join("\n  - ")}`, {
        hint: "this is a template bug (check its html() clips) — run `reelclaw check " + name + "` for details",
      });
    }
  }

  /** @type {MakeResult} */
  const out = { name, templateId: template.id, html, props, duration: result.timeline.duration, warnings };
  if (o.render) {
    const r = await renderReel({ root, name, quality: o.quality, workers: o.workers, log });
    log.success(`${displayPath(cwd, r.output)}  (${r.duration}s)`);
    out.output = r.output;
  }
  return out;
}

/**
 * Stage every media input (and media list items) in parallel.
 * @param {{ template: AnyTemplate, values: Record<string, unknown>, root: string, cwd: string, log: Logger }} o
 * @returns {Promise<Record<string, any>>}
 */
async function stageInputs({ template, values, root, cwd, log }) {
  /** @type {Record<string, any>} */
  const out = { ...values };
  const jobs = [];
  for (const [key, spec] of Object.entries(template.inputs)) {
    const v = values[key];
    if (v === undefined) continue;
    if (isMediaKind(spec.kind)) {
      const kind = /** @type {MediaKind} */ (spec.kind);
      jobs.push(stageMedia({ root, value: String(v), kind, label: flagName(key), cwd, log }).then((ref) => (out[key] = ref)));
    } else if (spec.kind === "list" && spec.item && isMediaKind(spec.item.kind) && Array.isArray(v)) {
      const kind = /** @type {MediaKind} */ (spec.item.kind);
      out[key] = [];
      v.forEach((item, i) => {
        jobs.push(stageMedia({ root, value: String(item), kind, label: `${flagName(key)}[${i + 1}]`, cwd, log }).then((ref) => (out[key][i] = ref)));
      });
    }
  }
  if (jobs.length) log.step(`staging ${jobs.length} media file(s)…`);
  await Promise.all(jobs);
  return out;
}

/**
 * The props snapshot saved next to a reel: media replaced by their staged
 * project paths so `make --props reels/<name>.json` reproduces it from the project root.
 * @param {AnyTemplate} template
 * @param {Record<string, unknown>} parsed
 * @param {Record<string, any>} staged
 */
function propsFor(template, parsed, staged) {
  /** @type {Record<string, unknown>} */
  const out = {};
  for (const [key, spec] of Object.entries(template.inputs)) {
    const v = staged[key];
    if (v === undefined) continue;
    if (isMediaKind(spec.kind)) out[key] = v.src;
    else if (spec.kind === "list" && spec.item && isMediaKind(spec.item.kind)) out[key] = v.map((/** @type {MediaRef} */ r) => r.src);
    else out[key] = parsed[key];
  }
  return out;
}

/**
 * Read a props file: `{ "template"?: "...", "inputs": {...} }` or a flat inputs object.
 * Relative media paths inside it are resolved against `cwd` by makeReel.
 * @param {string} file
 * @returns {Promise<{ template?: string, inputs: Record<string, unknown> }>}
 */
export async function readProps(file) {
  const abs = isAbsolute(file) ? file : resolve(file);
  if (!existsSync(abs)) throw new ReelclawError(`props file not found: ${file}`);
  let data;
  try {
    data = JSON.parse(await readFile(abs, "utf8"));
  } catch (cause) {
    throw new ReelclawError(`${file} is not valid JSON: ${/** @type {Error} */ (cause).message}`);
  }
  if (!data || typeof data !== "object" || Array.isArray(data)) throw new ReelclawError(`${file} must contain a JSON object`);
  if (data.inputs && typeof data.inputs === "object") return { template: data.template, inputs: data.inputs };
  const { template, $schema, ...inputs } = data;
  return { template, inputs };
}
